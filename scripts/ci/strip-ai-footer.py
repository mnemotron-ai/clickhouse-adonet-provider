#!/usr/bin/env python3
"""strip-ai-footer.py -- remove AI attribution lines from PR bodies and comments.

Owner's rule (Mike, 08.11.2026): no "Generated with/by Claude Code",
"Co-Authored-By: Claude", "Claude-Session:" or claude.ai session links in
anything posted to this repository. The cloud GitHub integration appends such
a footer on every write it makes, so the cleanup runs here, as github-actions
with GITHUB_TOKEN: its edits do not trigger workflows again and the
integration does not touch them.

Modes:
  --event     the PR or comment from $GITHUB_EVENT_PATH (pull_request,
              pull_request_target, issue_comment, pull_request_review_comment)
  --sweep     every open PR of $GITHUB_REPOSITORY: body, comments, review comments
  --push      post-merge alert: commits of a push to main whose message
              carries such a line (GitHub's squash merge adds
              "Co-authored-by: Claude" on its own, main dd0dec73 #1879). History
              is not rewritten; the job goes red and names the commit.
  --selftest  red/green legs on synthetic text, no network
"""
import json
import os
import re
import sys
import urllib.request

LABEL = "STRIP-AI-FOOTER"
LINE = re.compile(
    r"(Generated (with|by) \[?Claude Code|Co-Authored-By:\s*Claude|Claude-Session:"
    r"|claude\.ai/code/session_|_Requested by \*\*[^*]+\*\* · \[project thread\])",
    re.I,
)
TRAIL = re.compile(r"(\n[ \t]*(-{3,}|\*{3,}|_{3,})?[ \t]*)+\Z")


def clean(text):
    if not text or not LINE.search(text):
        return None
    kept = [l for l in text.split("\n") if not LINE.search(l)]
    out = TRAIL.sub("", "\n".join(kept)).strip("\n")
    return out + "\n" if out else ""


def api(method, path, body=None):
    url = os.environ.get("GITHUB_API_URL", "https://api.github.com") + path
    req = urllib.request.Request(url, method=method, data=None if body is None else json.dumps(body).encode())
    req.add_header("Authorization", "Bearer " + os.environ["GITHUB_TOKEN"])
    req.add_header("Accept", "application/vnd.github+json")
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.loads(r.read() or b"null")


def pages(path):
    page = 1
    while True:
        sep = "&" if "?" in path else "?"
        items = api("GET", f"{path}{sep}per_page=100&page={page}")
        if not items:
            return
        yield from items
        page += 1


def fix(kind, path, text):
    new = clean(text)
    if new is None:
        return 0
    api("PATCH", path, {"body": new})
    print(f"{LABEL} stripped {kind} {path}")
    return 1


def event():
    repo = os.environ["GITHUB_REPOSITORY"]
    ev = json.load(open(os.environ["GITHUB_EVENT_PATH"]))
    n = 0
    if "comment" in ev:
        c = ev["comment"]
        kind = "review-comment" if "pull_request_review_id" in c else "comment"
        sub = "pulls/comments" if kind == "review-comment" else "issues/comments"
        n += fix(kind, f"/repos/{repo}/{sub}/{c['id']}", c.get("body"))
    elif "pull_request" in ev:
        pr = ev["pull_request"]
        n += fix("body", f"/repos/{repo}/pulls/{pr['number']}", pr.get("body"))
    print(f"{LABEL} event={os.environ.get('GITHUB_EVENT_NAME')} stripped={n}")


def sweep():
    repo = os.environ["GITHUB_REPOSITORY"]
    n = prs = 0
    for pr in pages(f"/repos/{repo}/pulls?state=open"):
        prs += 1
        num = pr["number"]
        n += fix("body", f"/repos/{repo}/pulls/{num}", pr.get("body"))
        for c in pages(f"/repos/{repo}/issues/{num}/comments"):
            n += fix("comment", f"/repos/{repo}/issues/comments/{c['id']}", c.get("body"))
        for c in pages(f"/repos/{repo}/pulls/{num}/comments"):
            n += fix("review-comment", f"/repos/{repo}/pulls/comments/{c['id']}", c.get("body"))
    print(f"{LABEL} sweep open-prs={prs} stripped={n}")


def push():
    ev = json.load(open(os.environ["GITHUB_EVENT_PATH"]))
    bad = [(c["id"][:8], l) for c in ev.get("commits", []) for l in c.get("message", "").split("\n") if LINE.search(l)]
    for sha, l in bad:
        print(f"::error::{LABEL}: commit {sha} on main carries AI attribution: {l.strip()}")
    print(f"{LABEL} push commits={len(ev.get('commits', []))} with-trailers={len({s for s, _ in bad})}")
    if bad:
        print("Merge with an explicit commit message without trailers (squash default adds Co-authored-by).")
    return 1 if bad else 0


def selftest():
    red = ("## What\nfix\n\n---\n_Generated by [Claude Code](https://claude.ai/code/session_1)_\n",
           "x\n\nCo-Authored-By: Claude Opus <noreply@anthropic.com>\n",
           "<!-- claude-projects-attribution: {} -->\n_Requested by **Mike** · [project thread](https://claude.ai/code/project/c)_\n\nbody\n",
           "a\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)\n\nhttps://claude.ai/code/session_01X\n")
    want = ("## What\nfix\n", "x\n", "<!-- claude-projects-attribution: {} -->\n\nbody\n", "a\n")
    for r, w in zip(red, want):
        got = clean(r)
        if got != w:
            print(f"SELFTEST-{LABEL} FAIL: {r!r} -> {got!r}, want {w!r}")
            return 1
    for g in ("plain body\n", "Claude Code is named in prose here\n---\nend\n"):
        if clean(g) is not None:
            print(f"SELFTEST-{LABEL} FAIL: green leg changed {g!r}")
            return 1
    print(f"SELFTEST-{LABEL} red={len(red)} green=2 ok")
    return 0


if __name__ == "__main__":
    mode = sys.argv[1:] or ["--event"]
    if mode == ["--selftest"]:
        sys.exit(selftest())
    if mode == ["--push"]:
        sys.exit(push())
    if mode == ["--sweep"]:
        sweep()
    else:
        event()
